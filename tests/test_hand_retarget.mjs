import * as THREE from '../web/vendor/build/three.module.js';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=readFileSync(new URL('../web/avatar3d.js',import.meta.url),'utf8');
const basisSource=source.slice(source.indexOf('function palmBasis('),source.indexOf('\nfunction rememberPalm('));
const aimSource=source.slice(source.indexOf('function aim('),source.indexOf('\nfunction pose('));
const parent=new THREE.Bone(),node=new THREE.Bone();parent.add(node);
const bind=new THREE.Quaternion().setFromEuler(new THREE.Euler(.2,.4,.7));node.quaternion.copy(bind);
parent.quaternion.setFromEuler(new THREE.Euler(.1,-.3,.2));parent.updateMatrixWorld(true);
const context=vm.createContext({THREE,directions:new Map([['finger',new THREE.Vector3(0,1,0)]]),bone:()=>node,vrm:{humanoid:{getRestRotation:()=>bind}}});
vm.runInContext(basisSource+'\n'+aimSource,context);
const y=new THREE.Vector3(0,1,0),x=new THREE.Vector3(1,0,0);
assert.equal(context.palmBasis(y,x).angleTo(new THREE.Quaternion()),0);
assert.equal(context.palmBasis(y,y),null);
const rotation=new THREE.Quaternion().setFromEuler(new THREE.Euler(.6,-.4,1.2));
assert.ok(context.palmBasis(y.clone().applyQuaternion(rotation),x.clone().applyQuaternion(rotation)).angleTo(rotation)<1e-7);
const desired=y.clone().applyQuaternion(node.getWorldQuaternion(new THREE.Quaternion()));
context.aim('finger',[0,0,0],desired.toArray());assert.ok(node.quaternion.angleTo(bind)<1e-7,'rest rotation must retain its roll');
const next=new THREE.Vector3(.4,.2,-.8).normalize();context.aim('finger',[0,0,0],next.toArray());
assert.ok(y.clone().applyQuaternion(node.getWorldQuaternion(new THREE.Quaternion())).distanceTo(next)<1e-7,'bone must aim at the requested world direction under a rotated parent');
console.log('Hand retarget: 5 checks passed');
